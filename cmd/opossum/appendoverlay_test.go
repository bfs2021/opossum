// An overlay opossum wrote is not left behind when a later run finds an applied
// change: it is added to the end, as a second document, and the run uses it.
// Each row is one reason to add — or not to, or to say so.
func TestAppliedChangesFoundLaterAreAddedToAGeneratedOverlay(t *testing.T) {
	const generated = "# Generated by `opossum up --from-docker-compose`.\n#\n# my own note, kept\nservices: {}\n"
	for _, tc := range []struct {
		name      string
		overlay   string
		dirHolds  bool // the host directory has a file in it
		args      []string
		wantAdded bool
		wantMsg   string
		wantStays string // the message when it is left alone
	}{
		{name: "empty directory is added", overlay: generated, wantAdded: true, wantMsg: "added 1 change(s)"},
		{name: "a file ending without a newline still gets a blank line before the addition", overlay: strings.TrimSuffix(generated, "\n"), wantAdded: true, wantMsg: "added 1 change(s)"},
		{name: "a file in the directory is not", overlay: generated, dirHolds: true, wantStays: "already exists"},
		{name: "a file opossum did not write is not", overlay: "services: {}\n", wantStays: "already exists"},
		{name: "dry run shows it and writes nothing", overlay: generated, args: []string{"--dry-run"}, wantMsg: "would add 1 change(s)"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fakeShim(t)
			dir := t.TempDir()
			if err := os.MkdirAll(filepath.Join(dir, "content"), 0o755); err != nil {
				t.Fatal(err)
			}
			if tc.dirHolds {
				if err := os.WriteFile(filepath.Join(dir, "content", "keep"), []byte("x"), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			must := func(name, body string) {
				if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
					t.Fatal(err)
				}
			}
			must("compose.yaml", "name: demo\nservices:\n  blog:\n    image: ghost:6-alpine\n    volumes:\n      - ./content:/var/lib/ghost/content\n")
			must("compose.opossum.yaml", tc.overlay)
			if err := os.MkdirAll(filepath.Join(dir, ".opossum"), 0o755); err != nil {
				t.Fatal(err)
			}
			must(filepath.Join(".opossum", "chown-failures.json"), `[{"service":"blog","target":"/var/lib/ghost/content","source":"./content"}]`)
			t.Chdir(dir)

			args := append([]string{"up", "--from-docker-compose", "--no-build"}, tc.args...)
			out, err := run(t, args...)
			if err != nil {
				t.Fatalf("up: %v\n%s", err, out)
			}
			got, _ := os.ReadFile(filepath.Join(dir, "compose.opossum.yaml"))
			if tc.wantAdded {
				if !strings.HasPrefix(string(got), tc.overlay) {
					t.Errorf("what was in the file must stay exactly as it was, got:\n%s", got)
				}
				if !strings.Contains(string(got), "\n---\nservices:\n") || !strings.Contains(string(got), "blog-content:/var/lib/ghost/content") ||
					!strings.Contains(string(got), "\nvolumes:\n  blog-content: {}") {
					t.Errorf("the change should be a second document with its volume, got:\n%s", got)
				}
				if !strings.Contains(string(got), "\n\n# ── Added later") {
					t.Errorf("the addition stands apart from what was there, got:\n%s", got)
				}
				if st, err := os.Stat(filepath.Join(dir, "compose.opossum.yaml")); err != nil || st.Mode().Perm() != 0o644 {
					t.Errorf("the file keeps its own mode, got %v (%v)", st.Mode().Perm(), err)
				}
				if strings.Contains(out, "already exists") {
					t.Errorf("it was added, so nothing was left alone:\n%s", out)
				}
				// The next run has nothing left to add.
				again, err := run(t, args...)
				if err != nil {
					t.Fatalf("second up: %v\n%s", err, again)
				}
				after, _ := os.ReadFile(filepath.Join(dir, "compose.opossum.yaml"))
				if string(after) != string(got) {
					t.Errorf("a second run must not add the same thing again:\n%s", after)
				}
				return
			}
			if string(got) != tc.overlay {
				t.Errorf("the file must be left exactly as it was, got:\n%s", got)
			}
			if tc.wantMsg != "" && !strings.Contains(out, tc.wantMsg) {
				t.Errorf("want %q on screen, got:\n%s", tc.wantMsg, out)
			}
			if tc.wantStays != "" && !strings.Contains(out, tc.wantStays) {
				t.Errorf("want %q on screen, got:\n%s", tc.wantStays, out)
			}
		})
	}
}

// What replaces the overlay has to load first; if it does not, the file is as it
// was and nothing is left beside it.
func TestReplaceOverlayLeavesTheFileAloneWhenTheResultDoesNotLoad(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "compose.yaml"), []byte("services:\n  a:\n    image: x\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "compose.opossum.yaml")
	const before = "# Generated by `opossum up --from-docker-compose`.\nservices: {}\n"
	if err := os.WriteFile(path, []byte(before), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := replaceOverlay(dir, path, before+"\n---\nservices:\n  a: [not, a, mapping\n"); err == nil {
		t.Fatal("a result that does not load must be refused")
	}
	if got, _ := os.ReadFile(path); string(got) != before {
		t.Errorf("the file must be as it was, got:\n%s", got)
	}
	ents, _ := os.ReadDir(dir)
	for _, e := range ents {
		if strings.HasSuffix(e.Name(), ".tmp") {
			t.Errorf("a temporary file was left behind: %s", e.Name())
		}
	}
}

func writeProject(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

const chownCompose = "name: demo\nservices:\n  blog:\n    image: ghost:6-alpine\n    volumes:\n      - ./content:/var/lib/ghost/content\n"
const chownRecord = `[{"service":"blog","target":"/var/lib/ghost/content","source":"./content"}]`

// The run that adds to the overlay is the run that uses it, and --dry-run plans
// against the file as it would be — not as it stands.
func TestTheRunUsesWhatWasAdded(t *testing.T) {
	for _, dry := range []bool{false, true} {
		name := "real run"
		if dry {
			name = "dry run"
		}
		t.Run(name, func(t *testing.T) {
			calls := fakeShim(t)
			dir := writeProject(t, map[string]string{
				"compose.yaml":                 chownCompose,
				"content/.keep-dir":            "",
				"compose.opossum.yaml":         "# Generated by `opossum up --from-docker-compose`.\nservices: {}\n",
				".opossum/chown-failures.json": chownRecord,
			})
			if err := os.Remove(filepath.Join(dir, "content", ".keep-dir")); err != nil {
				t.Fatal(err)
			}
			t.Chdir(dir)
			args := []string{"up", "--from-docker-compose", "--no-build"}
			if dry {
				args = append(args, "--dry-run")
			}
			out, err := run(t, args...)
			if err != nil {
				t.Fatalf("up: %v\n%s", err, out)
			}
			seen := out
			if !dry {
				seen = strings.Join(calls(), "\n")
			}
			if !strings.Contains(seen, "blog-content:/var/lib/ghost/content") {
				t.Errorf("the service should start on the volume that was added, got:\n%s", seen)
			}
		})
	}
}

// Taking an entry out of the file is how a reader says no. Finding it again must
// not put it back — not when opossum wrote it and it is gone, not when the file
// is from before opossum kept that record.
func TestAnEntryTakenOutOfTheOverlayIsNotPutBack(t *testing.T) {
	const pg = "name: demo\nservices:\n  db:\n    image: postgres:16\n    volumes:\n      - ./pgdata:/var/lib/postgresql/data\n"
	for _, tc := range []struct {
		name       string
		forgetKeys bool
	}{
		{"the record says it was written", false},
		{"no record: a file from before it", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			fakeShim(t)
			dir := writeProject(t, map[string]string{"compose.yaml": pg})
			t.Chdir(dir)
			if out, err := run(t, "up", "--from-docker-compose", "--no-build"); err != nil {
				t.Fatalf("first up: %v\n%s", err, out)
			}
			// Take the entry out: header kept, nothing else.
			const emptied = "# Generated by `opossum up --from-docker-compose`.\nservices: {}\n"
			if err := os.WriteFile(filepath.Join(dir, "compose.opossum.yaml"), []byte(emptied), 0o644); err != nil {
				t.Fatal(err)
			}
			if tc.forgetKeys {
				if err := os.Remove(filepath.Join(dir, ".opossum", "overlay-entries.json")); err != nil {
					t.Fatal(err)
				}
			}
			out, err := run(t, "up", "--from-docker-compose", "--no-build")
			if err != nil {
				t.Fatalf("second up: %v\n%s", err, out)
			}
			got, _ := os.ReadFile(filepath.Join(dir, "compose.opossum.yaml"))
			if string(got) != emptied {
				t.Errorf("what the reader took out must stay out, got:\n%s", got)
			}
			if !strings.Contains(out, "not added again") {
				t.Errorf("it should say it left them out, got:\n%s", out)
			}
		})
	}
}

// A service that was not part of the first run — a profile turned on later — is
// new, whatever the record holds.
func TestAServiceTheFirstRunDidNotSeeIsAdded(t *testing.T) {
	fakeShim(t)
	t.Setenv("COMPOSE_PROFILES", "")
	dir := writeProject(t, map[string]string{"compose.yaml": "name: demo\nservices:\n  pg:\n    image: postgres:16\n    volumes:\n      - ./pg:/var/lib/postgresql/data\n" +
		"  db:\n    image: postgres:16\n    profiles: [debug]\n    volumes:\n      - ./dbdata:/var/lib/postgresql/data\n"})
	t.Chdir(dir)
	if out, err := run(t, "up", "--from-docker-compose", "--no-build", "--no-supervisor"); err != nil {
		t.Fatalf("first up: %v\n%s", err, out)
	}
	out, err := run(t, "up", "--from-docker-compose", "--no-build", "--no-supervisor", "--profile", "debug")
	if err != nil {
		t.Fatalf("second up: %v\n%s", err, out)
	}
	got, _ := os.ReadFile(filepath.Join(dir, "compose.opossum.yaml"))
	if !strings.Contains(string(got), "\n---\n") || !strings.Contains(string(got), "db-data:/var/lib/postgresql/data") {
		t.Errorf("the profile's service should be added, got:\n%s", got)
	}
}

// What needs a decision is still said, with the way to have it written; and a
// link is not turned into a file.
func TestWhatIsLeftIsSaidAndALinkIsLeftAlone(t *testing.T) {
	fakeShim(t)
	files := map[string]string{
		"compose.yaml":                 chownCompose + "  web:\n    image: busybox\n    volumes:\n      - shared:/srv\n  worker:\n    image: busybox\n    volumes:\n      - shared:/srv\nvolumes:\n  shared: {}\n",
		"content/.x":                   "",
		"real.yaml":                    "# Generated by `opossum up --from-docker-compose`.\nservices: {}\n",
		".opossum/chown-failures.json": chownRecord,
	}
	dir := writeProject(t, files)
	if err := os.Remove(filepath.Join(dir, "content", ".x")); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink("real.yaml", filepath.Join(dir, "compose.opossum.yaml")); err != nil {
		t.Fatal(err)
	}
	t.Chdir(dir)
	out, err := run(t, "up", "--from-docker-compose", "--no-build")
	if err != nil {
		t.Fatalf("up: %v\n%s", err, out)
	}
	if st, _ := os.Lstat(filepath.Join(dir, "compose.opossum.yaml")); st.Mode()&os.ModeSymlink == 0 {
		t.Error("a link must stay a link")
	}
	if got, _ := os.ReadFile(filepath.Join(dir, "real.yaml")); !strings.HasSuffix(string(got), "services: {}\n") || strings.Contains(string(got), "---") {
		t.Errorf("what the link points at is not ours to change, got:\n%s", got)
	}

	// A plain file: the applied one is added, the suggestion is said, with the way
	// to have it written.
	if err := os.Remove(filepath.Join(dir, "compose.opossum.yaml")); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "compose.opossum.yaml"), []byte(files["real.yaml"]), 0o644); err != nil {
		t.Fatal(err)
	}
	out, err = run(t, "up", "--from-docker-compose", "--no-build")
	if err != nil {
		t.Fatalf("second up: %v\n%s", err, out)
	}
	for _, want := range []string{"added 1 change(s)", "needs your decision", "shares named volume", "rm compose.opossum.yaml && opossum up --from-docker-compose"} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in:\n%s", want, out)
		}
	}
}
